import { writeIfChanged } from './fs.ts'
import { dirname, join, relative, sep } from 'node:path'
import type { BuiltSchema, LoadedSchema } from './schema-types.ts'

const projectRoot = join(import.meta.dir, '../..')
const builderPath = join(import.meta.dir, 'build-schema.ts')

const toImportPath =
  (fromDir: string, target: string) => {
    const path = relative(fromDir, target).split(sep).join('/')
    return path.startsWith('.') ? path : `./${path}`
  }

const assertIdentifier =
  (value: string) => {
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value))
      throw new Error(`Generated export name is not a valid identifier: "${value}"`)
    return value
  }

const isYamlSource =
  (source: string) => source.endsWith('.yaml') || source.endsWith('.yml')

export const buildExportsSource =
  (built: BuiltSchema, loaded: LoadedSchema[], exportPath: string) => {
    const exportDir = dirname(exportPath)
    const sortedLoaded =
      [...loaded].sort(
        (a, b) =>
          a.schema.title.localeCompare(b.schema.title)
          || a.importPath.localeCompare(b.importPath)
          || a.exportName.localeCompare(b.exportName))

    const inputLines =
      sortedLoaded.map(
        (schema, index) => {
          if (schema.source.endsWith('.json'))
            return `import input${index} from '${toImportPath(exportDir, schema.source)}'`
          // Purpose: drizzle-kit cannot import YAML, so its parsed documents are inlined
          if (isYamlSource(schema.source))
            return `const input${index} = ${JSON.stringify(schema.schema, null, 2)}`
          return `import { ${schema.exportName} as input${index} } from '${toImportPath(exportDir, schema.source)}'`
        })

    const inputEntries =
      sortedLoaded.map(
        (schema, index) =>
          `  { schema: input${index}`
          + `, source: ${JSON.stringify(schema.importPath)}`
          + `, importPath: ${JSON.stringify(schema.importPath)}`
          + `, exportName: ${JSON.stringify(schema.exportName)} }`)

    const exportLines =
      built.orderedTables.map(table => {
        const name = assertIdentifier(table.key)
        return `export const ${name} = builtSchema.tables['${table.key}'].drizzleSchema`
      })

    return [
      '// @generated by src/db/generate-migration.ts. Do not edit.',
      `import { buildSchema } from '${toImportPath(exportDir, builderPath)}'`,
      ...inputLines,
      '',
      'const builtSchema = buildSchema([',
      ...inputEntries.map(line => `${line},`),
      '])',
      '',
      ...exportLines,
      '',
    ].join('\n')
  }

export const writeExports =
  async (built: BuiltSchema, loaded: LoadedSchema[], exportPath: string) => {
    const changed =
      await writeIfChanged(
        exportPath, buildExportsSource(built, loaded, exportPath))
    return { path: exportPath, changed }
  }

export { projectRoot }
