import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, relative, sep } from 'node:path'
import type { BuiltSchema, LoadedSchema } from './schema-types.ts'

const projectRoot = join(import.meta.dir, '../..')
const builderPath = join(import.meta.dir, 'build-schema.ts')

const toImportPath =
  (fromDir: string, target: string) => {
    const path = relative(fromDir, target).split(sep).join('/')
    return path.startsWith('.') ? path : `./${path}`
  }

const assertIdentifier =
  (value: string) => {
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value))
      throw new Error(`Generated export name is not a valid identifier: "${value}"`)
    return value
  }

export const buildExportsSource =
  (built: BuiltSchema, loaded: LoadedSchema[], exportPath: string) => {
    const exportDir = dirname(exportPath)
    const sortedLoaded =
      [...loaded].sort(
        (a, b) =>
          a.schema.title.localeCompare(b.schema.title)
          || a.importPath.localeCompare(b.importPath)
          || a.exportName.localeCompare(b.exportName))

    const inputLines =
      sortedLoaded.map(
        (schema, index) =>
          `import { ${schema.exportName} as input${index} } from '${toImportPath(exportDir, schema.source)}'`)

    const exportLines =
      built.orderedTables.map(table => {
        const name = assertIdentifier(table.key)
        return `export const ${name} = builtSchema.tables['${table.key}'].drizzleSchema`
      })

    return [
      '// @generated by src/db/generate-migration.ts. Do not edit.',
      `import { buildSchema } from '${toImportPath(exportDir, builderPath)}'`,
      ...inputLines,
      '',
      `const builtSchema = buildSchema([${sortedLoaded.map((_, index) => `input${index}`).join(', ')}])`,
      '',
      ...exportLines,
      '',
    ].join('\n')
  }

export const writeExports =
  async (built: BuiltSchema, loaded: LoadedSchema[], exportPath: string) => {
    const source = buildExportsSource(built, loaded, exportPath)
    await mkdir(dirname(exportPath), { recursive: true })

    let previous = ''
    try {
      previous = await readFile(exportPath, 'utf8')
    } catch {
      // The file does not exist yet.
    }

    if (previous !== source)
      await writeFile(exportPath, source, 'utf8')

    return { path: exportPath, changed: previous !== source }
  }

export { projectRoot }
